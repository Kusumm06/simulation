"""Scene, IK, skin RCM, needle, approach planning."""
import numpy as np

from ultrabot_sim import config as cfg
from ultrabot_sim.approach import Approach
from ultrabot_sim.needle import NeedleModel
from ultrabot_sim.rcm import LockedLine, TrapezoidProfile, rcm_deviation
from ultrabot_sim.scene import joint_margin_deg


def test_homes_reached(scene):
    assert scene.home_ok
    e, a = scene.contact_err
    assert e < cfg.IK_TOL and a < cfg.IK_AXIS_TOL_DEG
    pose = scene.probe_pose(scene.ready_q["probe"])
    assert np.linalg.norm(pose.t - cfg.PROBE_SITE) < 1e-4
    assert np.allclose(pose.R[:, 0], cfg.PROBE_X_AXIS, atol=1e-5)


def test_ik_200_random_reachable_targets(scene):
    """Targets are generated by forward kinematics of random configurations
    around the working poses (so they are reachable); IK from the ready
    pose must hit them to < 0.1 mm and < 0.05 deg."""
    rng = np.random.default_rng(3)
    ok = 0
    for i in range(200):
        base = scene.ready_side_q[1 if i % 2 else -1]
        q = np.clip(np.asarray(base) + rng.normal(0, 0.25, 7),
                    np.array(cfg.JOINT_LOWER) * 0.95,
                    np.array(cfg.JOINT_UPPER) * 0.95)
        tip, d = scene.needle_axis(q)
        qs, e, a, m, good = scene.ik_needle_robust(tip, d, base, n_random=8)
        ok += int(e < cfg.IK_TOL and a < cfg.IK_AXIS_TOL_DEG)
    assert ok == 200


def test_unreachable_refused(scene):
    q, e, a, m, good = scene.ik_needle_robust(np.array([2.5, 2.5, 2.0]),
                                              np.array([0, 0, -1.0]),
                                              n_random=4)
    assert not good and e > cfg.IK_TOL


def test_rcm_during_insertion(scene, calib):
    pose = scene.probe_pose()
    E = np.array([cfg.US_WIDTH_MM / 2 + 10.0, 0.05])
    A = np.array([0.0, 14.0])
    d = (A - E) / np.linalg.norm(A - E)
    Ew = pose.probe_to_world([E[0], 0, E[1]])
    dw = pose.dir_probe_to_world([d[0], 0, d[1]])
    line = LockedLine(Ew, dw)
    q, *_ = scene.ik_needle_robust(line.tip(-0.01), dw, scene.ready_side_q[1])
    worst = 0.0
    for s in np.linspace(-0.01, 0.040, 200):
        q, e, a = scene.ik_needle(line.tip(s), dw, q, iters=80)
        tip, dd = scene.needle_axis(q)
        assert e < cfg.IK_TOL
        if s > 0:
            worst = max(worst, rcm_deviation(Ew, tip, dd) * 1000)
        assert joint_margin_deg(q) > 0
    assert worst < 0.5


def test_approach_collision_free(scene):
    ap = Approach(scene, seed=0)
    for a, b in ((scene.home_q["needle"], scene.ready_side_q[1]),
                 (scene.ready_side_q[1], scene.ready_side_q[-1])):
        jp = ap.plan("needle", a, b)
        assert jp is not None, ap.stats
        assert ap.validate("needle", jp)
        assert np.allclose(jp.q(jp.T), b, atol=1e-6)
        # speed limits respected
        ts = np.linspace(0, jp.T, 600)
        Q = np.array([jp.q(t) for t in ts])
        jv = np.max(np.abs(np.diff(Q, axis=0)) / np.diff(ts)[:, None])
        assert jv <= cfg.MAX_JOINT_VEL * 1.05
        P = np.array([scene.needle_axis(q)[0] for q in Q])
        tv = np.max(np.linalg.norm(np.diff(P, axis=0), axis=1) / np.diff(ts))
        assert tv <= cfg.MAX_TCP_SPEED * 1.05


def test_needle_throw_and_trapezoid():
    n = NeedleModel()
    n.fire()
    t = 0
    while not n.update(0.01):
        t += 0.01
    assert np.isclose(n.stylet_ext, cfg.THROW_MM)
    assert np.isclose(n.cannula_ext, cfg.THROW_MM)
    assert abs(t - cfg.FIRE_TIME_S) < 0.02
    tp = TrapezoidProfile(0, 20, 3, 6)
    assert np.isclose(tp.position(tp.T), 20)
    v = [tp.velocity(x) for x in np.linspace(0, tp.T, 200)]
    assert max(v) <= 3 + 1e-9
